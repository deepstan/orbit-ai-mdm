"""
RBAC + API-key authentication (Phase 3 item #1).

Replaces the old "trust the X-Tenant-Id header" approach (flagged as
insecure in earlier README versions) with real authentication: a caller
presents an API key, the key resolves to a `Principal` (tenant_id + role
+ optionally which domains it can touch), and every mutating action is
checked against that principal's permissions -- not a client-supplied
header.

Roles (per the architecture doc's Section 7):
  - tenant_admin  : everything within their tenant -- all domains, manage
                    API keys, retrain models, purge data (right-to-be-forgotten).
  - domain_admin  : full read/write within specific domains (set via
                    `allowed_domains` on the key), including retrain --
                    but can't manage API keys or purge data.
  - data_steward  : ingest + resolve the review queue within their
                    allowed domains. Can't retrain, manage keys, or purge.
  - api_consumer  : read-only within their allowed domains.
  - steward_agent : for an AI agent working next to the stewards (see docs/mcp-server.md): read-only, like api_consumer, PLUS it may read the audit sample. It cannot
                    ingest, resolve, unmerge, purge or administer anything. Its one write is `propose_decision`: it may RECORD a recommendation about a review item (which changes
                    nothing and is later compared with what a person decided); it never has `resolve_review_queue` unless a person upgrades the key.

No SSO provider (Auth0/Ory/Keycloak) integration here -- that needs a
real running service this sandbox can't reach. API keys are the
"real, working, zero-external-dependency" auth mechanism for this MVP;
swapping in SSO later means adding a second way to resolve a `Principal`
(e.g. from a validated JWT) alongside this one, not replacing this module.
"""
from __future__ import annotations

import hashlib
import os
import secrets
from dataclasses import dataclass, field
from typing import Optional

ROLES = ("tenant_admin", "domain_admin", "data_steward", "api_consumer", "steward_agent")

# action -> roles allowed to perform it. Checked via has_permission() below.
PERMISSIONS: dict[str, tuple[str, ...]] = {
    "ingest": ("tenant_admin", "domain_admin", "data_steward"),
    "resolve_review_queue": ("tenant_admin", "domain_admin", "data_steward"),
    "view": ("tenant_admin", "domain_admin", "data_steward", "api_consumer", "steward_agent"),
    "view_audits": ("tenant_admin", "domain_admin", "data_steward", "steward_agent"),
    "propose_decision": ("tenant_admin", "domain_admin", "steward_agent"),     # RECORD a recommendation about a review item; it changes nothing (resolving one is resolve_review_queue)   # read the sample of automatic merges (to check them is resolve_review_queue)
    "retrain": ("tenant_admin", "domain_admin"),
    "manage_api_keys": ("tenant_admin",),
    "purge": ("tenant_admin",),          # right-to-be-forgotten
    "view_audit_log": ("tenant_admin", "domain_admin"),
    "view_usage": ("tenant_admin",),
}


@dataclass
class Principal:
    """The resolved identity behind an authenticated request."""
    tenant_id: str
    role: str
    key_id: str
    label: str
    allowed_domains: Optional[list[str]] = field(default=None)  # None = all domains

    def can_access_domain(self, domain: str) -> bool:
        return self.allowed_domains is None or domain in self.allowed_domains

    def has_permission(self, action: str) -> bool:
        return self.role in PERMISSIONS.get(action, ())


class AuthError(Exception):
    """Raised for any authentication/authorization failure. api.py maps
    this to 401/403 as appropriate -- kept as one exception type here
    since this module has no HTTP framework knowledge of its own."""


def hash_key(plaintext_key: str) -> str:
    """API keys are high-entropy random tokens (32 bytes from
    secrets.token_urlsafe, ~43 chars, ~256 bits of entropy) generated by
    us, never user-chosen passwords -- so a fast hash (SHA-256) is
    appropriate here, unlike for passwords, where a deliberately slow
    hash (bcrypt/argon2) matters because passwords are often
    low-entropy and guessable. We never store the plaintext key."""
    return hashlib.sha256(plaintext_key.encode("utf-8")).hexdigest()


def generate_api_key() -> tuple[str, str]:
    """Returns (plaintext_key, key_hash). The plaintext is shown to the
    caller exactly once (at creation time) and never persisted -- only
    the hash is stored, so a database leak alone can't be used to
    authenticate."""
    plaintext = f"mdm_{secrets.token_urlsafe(32)}"
    return plaintext, hash_key(plaintext)


def check_permission(principal: Principal, action: str, domain: Optional[str] = None) -> None:
    """Raises AuthError if the principal can't perform `action` (and, if
    `domain` is given, can't perform it in that domain). Returns None
    (doesn't raise) on success -- call it for its side effect."""
    if not principal.has_permission(action):
        raise AuthError(f"Role '{principal.role}' is not permitted to perform '{action}'")
    if domain is not None and not principal.can_access_domain(domain):
        raise AuthError(f"API key '{principal.label}' is not scoped to domain '{domain}'")


# --------------------------------------------------------------------------- the choices that must not be left to the caller
DEV_MODE_ENV = "MDM_DEV_MODE"


def dev_mode() -> bool:
    """True ONLY when someone has said so: MDM_DEV_MODE=1/true/yes. Authentication is required otherwise. (It used to be the other way round: auth was off unless
    MDM_ENABLE_AUTH was set, so forgetting one variable in production left the whole API open to anyone naming a tenant in a header.)"""
    return os.environ.get(DEV_MODE_ENV, "").strip().lower() in ("1", "true", "yes")


def human_actor(principal: Principal) -> str:
    """The name recorded for a person's decision, taken from the authenticated key and NEVER from the request: 'steward:<key label>'. It cannot begin with
    'system:' (that prefix marks the system's own decisions, which are not training labels), whatever the label says."""
    return f"steward:{(principal.label or principal.key_id or 'unknown').strip()}"


MAX_LABEL = 100


def valid_key_label(label) -> str:
    """A key's label becomes the name on every decision made with that key: it must be a real, printable name, and must not pass as the system."""
    text = (label or "").strip() if isinstance(label, str) else ""
    if not text:
        raise ValueError("a key needs a label: it is the name recorded on every decision made with it")
    if len(text) > MAX_LABEL:
        raise ValueError(f"a key's label may be at most {MAX_LABEL} characters")
    if not text.isprintable():
        raise ValueError("a key's label may not contain control characters")
    if text.lower().startswith("system:"):
        raise ValueError("a key's label may not begin with 'system:': that marks the system's own decisions")
    return text


def visible_domains(principal: Principal, names) -> list:
    """The domains from `names` this key may see (all of them for a key with no domain restriction)."""
    return [n for n in names if principal.can_access_domain(n)]


def may_see_log_entry(principal: Principal, entry_domain) -> bool:
    """A key restricted to some domains sees only the audit-log entries of those domains: never the tenant-wide ones (a key created, a purge) and never other domains'."""
    return principal.allowed_domains is None or (entry_domain is not None and entry_domain in principal.allowed_domains)
